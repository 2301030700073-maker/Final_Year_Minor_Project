#!/usr/bin/env python3
"""Mechanical honesty audit over every stored report.

WHY (the user's standing concern): the pipeline's cardinal rule is that a report
must NEVER claim success/OK where the evidence says otherwise - "not detected"
is not "absent", a NEITHER/Inconclusive must never be promoted to a confident
negative, and "engagement" (Frida hooks loaded) must never be reported as a
confirmed bypass. A report that breaks that rule is worse than no report: it
actively misleads.

WHAT IT CHECKS (each report is audited against its OWN recorded facts - no
re-analysis, no re-run):

  1. a failed stage in the Stage Results table must not be narrated as success
     elsewhere (looks for the known over-claim phrases);
  2. a dynamic `success` must carry the "machinery ran; bypass not confirmed"
     qualifier when neither root nor SSL was confirmed (a confirmed bypass
     legitimately renders a bare `success`);
  3. an empty/absent capture must carry a recorded reason;
  4. "This run's decompilation" must not appear together with REUSED FROM CACHE;
  5. a coverage-limited NEITHER must carry the Coverage-limited caveat on the
     Decision line, and its dynamic skip must carry the COVERAGE-LIMITED clause;
  6. "Root bypassed: True" must be accompanied by probe evidence lines.

This is a read-only audit harness. It is also imported by
`tests/unit/test_report_honesty_audit.py`, which asserts that NO report
generated on/after the template-fix cutoff date carries a finding - i.e. the
generator cannot regress into lying.

Run directly: `python tools/report_honesty_audit.py [--since YYYY-MM-DD]`
"""
from __future__ import annotations

import argparse
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

# Default corpus location; overridable for tests.
ROOT = Path(__file__).resolve().parents[1] / "outputs" / "reports"

# Reports modified on/after this date are generated by the fixed templates and
# MUST be honest. Earlier reports are historical artifacts produced by the old
# templates (before the decompile-provenance and coverage-limited fixes) and are
# excluded from the regression assertion. Tie this to the commit that last fixed
# a report-template honesty bug.
REGRESSION_CUTOFF = "2026-10-21"


def stage_rows(text: str) -> dict[str, list[tuple[str, str]]]:
    rows: dict[str, list[tuple[str, str]]] = {}
    for m in re.finditer(
        r"^\|\s*([a-z_\-:() ]+?)\s*\|\s*(success|failed|skipped)([^|]*)\|",
        text,
        re.MULTILINE,
    ):
        rows.setdefault(m.group(1).strip(), []).append(
            (m.group(2), m.group(3).strip())
        )
    return rows


def audit(path: Path) -> list[str]:
    """Return a list of honesty findings for one report (empty = honest)."""
    text = path.read_text(encoding="utf-8", errors="replace")
    findings: list[str] = []
    rows = stage_rows(text)
    dec = "REUSED FROM CACHE" in text

    # 1. failed dynamic narrated as success anywhere
    dyn = rows.get("dynamic", [])
    if any(s == "failed" for s, _ in dyn):
        if re.search(
            r"Dynamic stage succeeded|dynamic bypass succeeded|all checks passed",
            text,
            re.I,
        ):
            findings.append("failed dynamic narrated as success")
    # 2. dynamic success without the qualifier - only a problem when the report
    # itself confirms NOTHING (both dimensions inconclusive/False/not-run); a
    # confirmed bypass legitimately renders a bare `success`.
    if any(s == "success" and "machinery ran" not in extra for s, extra in dyn):
        m = re.search(r"## Dynamic Verification(.*?)(?=\n## |\Z)", text, re.S)
        section = m.group(1) if m else ""
        root_line = re.search(r"Root bypassed:\s*(\w+)", section)
        ssl_line = re.search(r"SSL bypassed:\s*(\w+)", section)
        vals = {
            (root_line.group(1) if root_line else ""),
            (ssl_line.group(1) if ssl_line else ""),
        }
        if "True" not in vals:
            findings.append(
                "dynamic success row lacks the 'machinery ran' qualifier "
                "and no dimension is confirmed"
            )
    # 3. capture skipped with no recorded reason sentence
    cap = rows.get("capture-traffic", [])
    if cap and all(s == "skipped" for s, _ in cap):
        if "No traffic was captured" not in text and "not attempted" not in text.lower():
            findings.append("capture skipped with no recorded reason")
    # 4. cached decompile narrated as this run's
    if dec and "This run's decompilation" in text:
        findings.append("cached decompile narrated as 'This run's decompilation'")
    # 5. coverage-limited NEITHER without the caveat
    if "Decision:** NEITHER" in text and "not fully analyzed" in text:
        if "Coverage-limited" not in text:
            findings.append("coverage-limited NEITHER missing the Decision caveat")
        if "no bypass technique to apply" in text and "COVERAGE-LIMITED" not in text:
            findings.append("coverage-limited skip reason lacks the COVERAGE-LIMITED clause")
    # 6. root bypassed True with no probe evidence
    if "Root bypassed: True" in text and "probe" not in text.lower():
        findings.append("Root bypassed: True with no probe evidence line")
    return findings


def collect_findings(root: Path, since: str | None = None) -> dict[str, list[str]]:
    """Audit every report under `root`. When `since` (YYYY-MM-DD) is given, only
    reports whose mtime is on/after that date are included (the regression
    window). Returns {relative_path: [findings]} for reports that have findings."""
    since_dt = (
        datetime.strptime(since, "%Y-%m-%d").replace(tzinfo=timezone.utc)
        if since
        else None
    )
    out: dict[str, list[str]] = {}
    for p in sorted(root.glob("*/*.md")):
        if since_dt is not None:
            mt = datetime.fromtimestamp(p.stat().st_mtime, tz=timezone.utc)
            if mt < since_dt:
                continue
        f = audit(p)
        if f:
            out[str(p.relative_to(root))] = f
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Audit stored reports for honesty violations")
    ap.add_argument(
        "--since",
        default=None,
        help="Only audit reports modified on/after this YYYY-MM-DD (regression window)",
    )
    ap.add_argument("--root", default=str(ROOT), help="Override the reports directory")
    args = ap.parse_args(argv)

    root = Path(args.root)
    findings = collect_findings(root, since=args.since)
    total = sum(len(v) for v in findings.values())
    for rel, fs in findings.items():
        print(f"\n{rel}")
        for x in fs:
            print(f"  * {x}")
    print(f"\nreports_with_findings={len(findings)} findings={total}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
